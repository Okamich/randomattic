/**
 * Сгенерировать полноценную таверну по настройкам
 * @param {object} options
 * @returns {object}
 */
export function generateTavern(options = {}) {
  const adj = pickOne(ADJECTIVES);
  const noun = pickOne(NOUNS);
  const name = `«${adj} ${noun}»`;

  const keeperName = pickOne(INNKEEPER_NAMES);
  const keeperRace = pickOne(INNKEEPER_RACES);
  const keeperTrait = pickOne(INNKEEPER_TRAITS);
  const innkeeper = `${keeperName} (${keeperRace}), ${keeperTrait}`;

  const dish = pickOne(DISHES);
  const drink = pickOne(DRINKS);
  const rumor = pickOne(RUMORS);
  const event = pickOne(EVENTS);

  return {
    name,
    innkeeper,
    dish: `${dish.name} — ${formatCoins(dish.price)}`,
    drink: `${drink.name} — ${formatCoins(drink.price)}`,
    rumor,
    event
  };
}
