import openpyxl, sys, json, os

sys.stdout.reconfigure(encoding='utf-8')

def build_job_module():
    wb = openpyxl.load_workbook('files/NPC/npc_job.xlsx', data_only=True)
    sheet = wb.active
    jobs = []
    for r in range(2, sheet.max_row + 1):
        num = sheet.cell(r, 1).value
        title = sheet.cell(r, 2).value
        if title:
            jobs.append({
                "roll": int(num) if num else len(jobs) + 1,
                "titleRu": str(title).strip()
            })
    
    js_code = "/**\n * Randomattic - NPC 100 Occupations / Jobs (d100)\n * Compiled from files/NPC/npc_job.xlsx\n */\n\n"
    js_code += "export const NPC_JOBS_D100 = " + json.dumps(jobs, ensure_ascii=False, indent=2) + ";\n"
    
    out_path = os.path.join("js", "data", "npc-job-data.js")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(js_code)
    print(f"Generated {out_path} with {len(jobs)} jobs.")

