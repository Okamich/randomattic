import openpyxl, json, re

wb = openpyxl.load_workbook(r'files/Town/Генератор поселения.xlsx', data_only=True)

def cval(ws, r, c):
    v = ws.cell(r, c).value
    return str(v).strip() if v is not None else ''

def strip_num(s):
    if not s: return ''
    s = str(s).strip()
    return re.sub(r'^\d+[\.\-\–\s]+', '', s).strip()

